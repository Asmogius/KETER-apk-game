#!/usr/bin/env python3
"""KETER Lab: writes the card systems out of lab/spec_data.py for the two apps to read.

  game/data/lab_systems.json   the game (scripts/lab_systems.gd)
  lab_data.js                  the Companion (lab.js), as window.KETER_LAB_DATA

Every tier's keyword text is written out whole, so neither app has to build it:
an app only picks a tier and puts in the token. Run after changing spec_data.py:

  python3 lab/make_lab_systems.py
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import spec_data as D  # noqa: E402

VERSION = "L1"


def tiers_of(a):
    out = []
    for t in a["tiers"]:
        d = a["line"](t)
        out.append({"text": a["text"](t), "e": t.get("e"), "p": t.get("p", 0),
                    "dmg": d.get("dmg", 0), "rng": d.get("rng", 0), "hit": d.get("hit", 0)})
    return out


def menu_of(items):
    return [{"id": m["id"], "name": m["name"], "note": m["note"], "min": m["min"], "kind": m["kind"],
             "tiers": [{"text": m["text"](t), "cost": (m["cost"][i] if m["cost"] else None)} for i, t in enumerate(m["tiers"])]} for m in items]


def data():
    return {
        "format": 1, "version": VERSION,
        "roles": D.ROLES, "roleName": D.ROLE_NAME, "roleDoes": D.ROLE_DOES, "roleAttack": D.ROLE_ATTACK,
        "rarities": D.RARITIES, "sizes": D.SIZES,
        "troop": D.TROOP, "size": D.SIZE, "rarity": D.RARITY, "hero": D.HERO, "heroRarity": D.HERO_RARITY,
        "enemy": D.ENEMY, "enemySize": D.ENEMY_SIZE, "enemyTier": D.ENEMY_TIER, "enemyAbilities": D.ENEMY_ABILITIES, "grade": D.GRADE,
        "trades": [list(t) for t in D.TRADES], "statPrice": D.STAT_PRICE, "tierPrice": {str(k): v for k, v in D.TIER_PRICE.items()},
        "library": [{"id": a["id"], "name": a["name"], "kind": a["kind"], "roles": a["roles"], "does": a["does"], "min": a["min"], "tiers": tiers_of(a)} for a in D.A],
        "menus": {k: menu_of(v) for k, v in D.M.items()},
        "equipTriggers": [{"id": i, "name": n, "text": t} for i, n, t in D.EQUIP_TRIGGERS],
        "tokens": D.TOKENS, "core": D.CORE,
        "folds": [list(f) for f in D.FOLDS],
    }


def main():
    d = data()
    out = ROOT / "game" / "data" / "lab_systems.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    js = ("/* Generated by lab/make_lab_systems.py from lab/spec_data.py: KETER Lab's card systems, "
          "for lab.js. Don't edit by hand. */\nwindow.KETER_LAB_DATA=" + json.dumps(d, ensure_ascii=False, separators=(",", ":")) + ";\n")
    (ROOT / "lab_data.js").write_text(js, encoding="utf-8")
    print("lab systems %s: %d abilities, %d menu items -> %s, lab_data.js" % (VERSION, len(d["library"]), sum(len(v) for v in d["menus"].values()), out.relative_to(ROOT)))


if __name__ == "__main__":
    main()
